"""
LLM Orchestrator Master Module.

Provides the LLMOrchestrator class which coordinates Intent Classification,
Execution Planning, Knowledge Graph retrieval, Telemetry analytics, Document RAG,
Prompt Construction, and LLM synthesis into a unified AI Asset Intelligence assistant.
Executes services by iterating through an ExecutionPlan generated by ExecutionPlanner.
"""

import time
from typing import List, Optional

from .models import (
    Intent,
    ServiceCall,
    AssetContext,
    TelemetryContext,
    DocumentContext,
    PromptContext,
    OrchestratorResponse
)
from .execution_models import ExecutionPlan, PlanStep
from .execution_planner import ExecutionPlanner
from .intent_classifier import IntentClassifier
from .prompt_builder import PromptBuilder
from .llm_client import LLMClient

from graph.neo4j_client import Neo4jClient
from graph.graph_queries import GraphQueries
from telemetry.telemetry_reader import TelemetryService
from telemetry.telemetry_analysis import TelemetryAnalyzer
from documents.document_service import DocumentService, RetrievedDocumentChunk

from utils.logger import setup_logger
from utils.exceptions import AssetIntelligenceException, GraphQueryException, TelemetryException, DocumentException
from config import config

logger = setup_logger("llm.orchestrator", config.log_level)


class LLMOrchestrator:
    """Master orchestrator combining Graph, Telemetry, and Document services via an ExecutionPlan."""

    def __init__(
        self,
        graph_client: Optional[Neo4jClient] = None,
        telemetry_service: Optional[TelemetryService] = None,
        document_service: Optional[DocumentService] = None,
        llm_client: Optional[LLMClient] = None
    ) -> None:
        """
        Initialize LLMOrchestrator with references to subsystem services and execution planner.

        Args:
            graph_client (Optional[Neo4jClient]): Graph client instance.
            telemetry_service (Optional[TelemetryService]): Telemetry service instance.
            document_service (Optional[DocumentService]): Document service instance.
            llm_client (Optional[LLMClient]): LLM client instance.
        """
        self.graph_client = graph_client or Neo4jClient()
        self.telemetry_service = telemetry_service or TelemetryService()
        self.document_service = document_service or DocumentService()
        self.intent_classifier = IntentClassifier()
        self.execution_planner = ExecutionPlanner()
        self.prompt_builder = PromptBuilder()
        self.llm_client = llm_client or LLMClient()

    def process_query(self, user_question: str) -> OrchestratorResponse:
        """
        Process user question end-to-end: classify intent, generate execution plan,
        execute plan steps across required services, construct prompt, invoke LLM, and return response.

        Args:
            user_question (str): Input natural language question.

        Returns:
            OrchestratorResponse: Structured output bundle containing answer, execution plan, and metrics.
        """
        start_total = time.perf_counter()
        logger.info("Processing orchestrator query: '%s'...", user_question)

        # Step 1: Intent Classification
        t0 = time.perf_counter()
        intent: Intent = self.intent_classifier.classify(user_question)
        t_intent = (time.perf_counter() - t0) * 1000.0

        service_calls: List[ServiceCall] = [
            ServiceCall(service="IntentClassifier", success=True, execution_time_ms=t_intent, records_returned=1)
        ]

        # Step 2: Execution Planning
        t0 = time.perf_counter()
        plan: ExecutionPlan = self.execution_planner.create_plan(user_question, intent)
        t_plan = (time.perf_counter() - t0) * 1000.0
        service_calls.append(ServiceCall(service="ExecutionPlanner", success=True, execution_time_ms=t_plan, records_returned=len(plan.steps)))

        graph_ctx: Optional[AssetContext] = None
        telemetry_ctx: Optional[TelemetryContext] = None
        document_ctx: Optional[DocumentContext] = None

        # Step 3: Iterate and Execute Plan Steps
        for step in plan.steps:
            logger.info("Executing plan step '%s' [%s]: %s", step.step_id, step.service_name, step.action)

            # Execution Step: GraphService
            if step.service_name == "GraphService":
                t0 = time.perf_counter()
                try:
                    self.graph_client.connect()
                    g_queries = GraphQueries(self.graph_client)
                    asset_id = step.params.get("asset_id", "AHU-01")

                    asset_info = g_queries.get_asset(asset_id)
                    components = g_queries.get_components(asset_id)
                    spaces = g_queries.get_served_spaces(asset_id)
                    health = g_queries.get_health_status(asset_id)
                    state = g_queries.get_operating_state(asset_id)
                    manufacturer = g_queries.get_manufacturer(asset_id)
                    docs = g_queries.get_documents(asset_id)
                    telemetry_streams = g_queries.get_telemetry_streams(asset_id)
                    maintenance = g_queries.get_maintenance_history(asset_id)

                    graph_ctx = AssetContext(
                        asset_id=asset_id,
                        asset_info=asset_info,
                        components=components,
                        served_spaces=spaces,
                        health_status=health,
                        operating_state=state,
                        manufacturer=manufacturer,
                        documents=docs,
                        telemetry_streams=telemetry_streams,
                        maintenance_history=maintenance
                    )
                    rec_count = len(components) + len(spaces) + len(docs) + len(maintenance)
                    t_step = (time.perf_counter() - t0) * 1000.0
                    service_calls.append(ServiceCall(service="GraphService", success=True, execution_time_ms=t_step, records_returned=rec_count))
                    logger.info("GraphService step executed successfully in %.1f ms (%d records).", t_step, rec_count)
                except Exception as e:
                    t_step = (time.perf_counter() - t0) * 1000.0
                    logger.warning("GraphService step failed (%s). Continuing with remaining plan steps.", e)
                    service_calls.append(ServiceCall(service="GraphService", success=False, execution_time_ms=t_step, records_returned=0, error_message=str(e)))

            # Execution Step: TelemetryService
            elif step.service_name == "TelemetryService":
                t0 = time.perf_counter()
                try:
                    csv_file = "sample_ahu_telemetry.csv"
                    if graph_ctx and graph_ctx.telemetry_streams:
                        csv_file = graph_ctx.telemetry_streams[0].get("storage", csv_file)

                    df = self.telemetry_service.load_stream(csv_file)
                    analyzer = TelemetryAnalyzer(df)

                    metrics = analyzer.get_available_metrics()
                    latest = {m: analyzer.latest_value(m) for m in metrics}
                    averages = {m: analyzer.average(m) for m in metrics}
                    stats = analyzer.statistics("supply_air_temperature")

                    anomalies = {
                        "supply_air_temperature": analyzer.detect_simple_anomalies("supply_air_temperature", z_threshold=2.5),
                        "filter_pressure_drop": analyzer.detect_simple_anomalies("filter_pressure_drop", z_threshold=2.5),
                        "fan_rpm": analyzer.detect_simple_anomalies("fan_rpm", z_threshold=2.5)
                    }

                    telemetry_ctx = TelemetryContext(
                        metrics_available=metrics,
                        latest_readings=latest,
                        averages=averages,
                        statistics=stats,
                        anomalies=anomalies
                    )
                    rec_count = len(latest) + sum(len(v) for v in anomalies.values())
                    t_step = (time.perf_counter() - t0) * 1000.0
                    service_calls.append(ServiceCall(service="TelemetryService", success=True, execution_time_ms=t_step, records_returned=rec_count))
                    logger.info("TelemetryService step executed successfully in %.1f ms (%d records).", t_step, rec_count)
                except Exception as e:
                    t_step = (time.perf_counter() - t0) * 1000.0
                    logger.warning("TelemetryService step failed (%s). Continuing with remaining plan steps.", e)
                    service_calls.append(ServiceCall(service="TelemetryService", success=False, execution_time_ms=t_step, records_returned=0, error_message=str(e)))

            # Execution Step: DocumentService
            elif step.service_name == "DocumentService":
                t0 = time.perf_counter()
                try:
                    doc_path = "documents/39M-22PD.pdf"
                    if graph_ctx and graph_ctx.documents:
                        doc_path = graph_ctx.documents[0].get("location", doc_path)

                    self.document_service.build_index([doc_path])
                    query_str = step.params.get("query", user_question)
                    top_k = step.params.get("top_k", 3)
                    chunks: List[RetrievedDocumentChunk] = self.document_service.query(query_str, top_k=top_k)

                    document_ctx = DocumentContext(query=query_str, retrieved_chunks=chunks)
                    t_step = (time.perf_counter() - t0) * 1000.0
                    service_calls.append(ServiceCall(service="DocumentService", success=True, execution_time_ms=t_step, records_returned=len(chunks)))
                    logger.info("DocumentService step executed successfully in %.1f ms (%d chunks).", t_step, len(chunks))
                except Exception as e:
                    t_step = (time.perf_counter() - t0) * 1000.0
                    logger.warning("DocumentService step failed (%s). Continuing with remaining plan steps.", e)
                    service_calls.append(ServiceCall(service="DocumentService", success=False, execution_time_ms=t_step, records_returned=0, error_message=str(e)))

        # Step 4: Prompt Construction
        t0 = time.perf_counter()
        prompt_ctx = PromptContext(
            user_question=user_question,
            intent=intent,
            graph_context=graph_ctx,
            telemetry_context=telemetry_ctx,
            document_context=document_ctx
        )
        prompt_str = self.prompt_builder.build_prompt(prompt_ctx)
        t_prompt = (time.perf_counter() - t0) * 1000.0
        service_calls.append(ServiceCall(service="PromptBuilder", success=True, execution_time_ms=t_prompt, records_returned=1))

        # Step 5: LLM Generation
        t0 = time.perf_counter()
        final_answer = self.llm_client.generate_response(prompt_str)
        t_llm = (time.perf_counter() - t0) * 1000.0
        service_calls.append(ServiceCall(service="LLMClient", success=True, execution_time_ms=t_llm, records_returned=1))

        total_time_ms = (time.perf_counter() - start_total) * 1000.0

        return OrchestratorResponse(
            user_question=user_question,
            intent=intent,
            service_calls=service_calls,
            prompt_used=prompt_str,
            raw_llm_response=final_answer,
            final_answer=final_answer,
            total_execution_time_ms=round(total_time_ms, 2),
            execution_plan=plan,
            graph_context=graph_ctx,
            telemetry_context=telemetry_ctx,
            document_context=document_ctx,
            llm_backend=self.llm_client.last_backend
        )
